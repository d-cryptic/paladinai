package eval

import (
	"context"
	"fmt"
	"time"

	"go.uber.org/zap"
)

// RunConfig configures a Runner.
type RunConfig struct {
	FixturesDir string
	Categories  []Category    // nil = all
	MaxCases    int           // 0 = all
	Timeout     time.Duration // per-case timeout; 0 = none
}

// CategoryResult aggregates results for a single category.
type CategoryResult struct {
	Total     int
	Passed    int
	PassRate  float64
	MeanScore float64
}

// RunResult is the result of a Runner.Run call.
type RunResult struct {
	Total      int
	Passed     int
	Failed     int
	Skipped    int
	PassRate   float64
	MeanScore  float64
	ByCategory map[Category]*CategoryResult
	Scores     []Score
	Duration   time.Duration
}

// ScoreFunc receives a test case and a response string and returns a Score.
// This indirection keeps the runner model-agnostic — callers wire in either
// a static response (CI mode) or a real LLM/agent call.
type ScoreFunc func(tc TestCase, response string) Score

// ResponseFunc produces the response string for a given test case. CI mode
// uses a trivial implementation; real evals call into agents.
type ResponseFunc func(ctx context.Context, tc TestCase) (string, error)

// Runner executes eval test cases against a provided scoring function.
type Runner struct {
	cfg RunConfig
	log *zap.Logger
}

// NewRunner constructs a Runner. If log is nil, a no-op logger is used.
func NewRunner(cfg RunConfig, log *zap.Logger) *Runner {
	if log == nil {
		log = zap.NewNop()
	}
	return &Runner{cfg: cfg, log: log}
}

// Run loads fixtures from cfg.FixturesDir, optionally filters by category,
// and applies scoreFn to each test case. The response is generated by respFn
// (which may be a static empty-string producer in CI mode).
func (r *Runner) Run(
	ctx context.Context,
	respFn ResponseFunc,
	scoreFn ScoreFunc,
) (*RunResult, error) {
	if scoreFn == nil {
		return nil, fmt.Errorf("scoreFn is required")
	}
	if respFn == nil {
		respFn = func(context.Context, TestCase) (string, error) { return "", nil }
	}

	start := time.Now()

	cases, err := LoadFixtures(r.cfg.FixturesDir)
	if err != nil {
		return nil, fmt.Errorf("load fixtures: %w", err)
	}

	wanted := categorySet(r.cfg.Categories)
	result := &RunResult{
		ByCategory: make(map[Category]*CategoryResult),
	}

	for _, tc := range cases {
		if len(wanted) > 0 {
			if _, ok := wanted[tc.Category]; !ok {
				result.Skipped++
				continue
			}
		}
		if r.cfg.MaxCases > 0 && result.Total >= r.cfg.MaxCases {
			result.Skipped++
			continue
		}

		caseCtx := ctx
		var cancel context.CancelFunc
		if r.cfg.Timeout > 0 {
			caseCtx, cancel = context.WithTimeout(ctx, r.cfg.Timeout)
		}

		response, err := respFn(caseCtx, tc)
		if cancel != nil {
			cancel()
		}
		if err != nil {
			r.log.Warn("response func failed",
				zap.String("id", tc.ID),
				zap.Error(err),
			)
			result.Failed++
			result.Total++
			score := Score{TestID: tc.ID, Category: tc.Category, Pass: false, Score: 0, Details: err.Error()}
			result.Scores = append(result.Scores, score)
			recordCategory(result.ByCategory, score)
			continue
		}

		score := scoreFn(tc, response)
		score.TestID = tc.ID
		score.Category = tc.Category
		result.Scores = append(result.Scores, score)

		result.Total++
		if score.Pass {
			result.Passed++
		} else {
			result.Failed++
		}
		recordCategory(result.ByCategory, score)
	}

	if result.Total > 0 {
		result.PassRate, result.MeanScore = AggregateResults(result.Scores)
	}
	for _, cat := range result.ByCategory {
		if cat.Total > 0 {
			cat.PassRate = float64(cat.Passed) / float64(cat.Total)
			cat.MeanScore = cat.MeanScore / float64(cat.Total)
		}
	}
	result.Duration = time.Since(start)
	return result, nil
}

func categorySet(cats []Category) map[Category]struct{} {
	m := make(map[Category]struct{}, len(cats))
	for _, c := range cats {
		m[c] = struct{}{}
	}
	return m
}

func recordCategory(byCat map[Category]*CategoryResult, s Score) {
	cat, ok := byCat[s.Category]
	if !ok {
		cat = &CategoryResult{}
		byCat[s.Category] = cat
	}
	cat.Total++
	if s.Pass {
		cat.Passed++
	}
	cat.MeanScore += s.Score
}
